#ifndef __NTC_H
#define __NTC_H

#include "stm32f10x.h"

/**
  ******************************************************************************
  * @file    NTC.h
  * @brief   NTC 热敏电阻 + LM393 温度模块驱动（AO 模拟输出 + DO 开关量输出）
  *
  * 模块引脚与接线：
  *   VCC -> 3.3V
  *   GND -> GND
  *   AO  -> PA0（ADC1_IN0，模拟电压，随温度连续变化）
  *   DO  -> PB13（比较器输出，超过电位器设定阈值时翻转，上拉输入）
  *
  * AO 的换算见 NTC.c 顶部的宏：默认按“10k NTC（B=3950）+ 10k 分压，NTC 在下臂”建模，
  * 如果你这块板子实测对不上，改那几个宏即可（README 有标定方法）。
  ******************************************************************************
  */

/* 初始化：PA0 配成模拟输入并校准 ADC1；PB13 配成上拉输入用于读 DO。 */
void NTC_Init(void);

/* 启动一次 ADC1 单次转换并等待结束，返回 0~4095 的原始码值。 */
uint16_t NTC_ReadAdc(void);

/* 把 ADC 码值换算成温度，单位 0.1℃（如 253 表示 25.3℃）。
 * 内部按分压反推 NTC 阻值，再用 B 值公式算温度；异常输入会被钳到 -55~125℃。 */
int16_t NTC_AdcToTempX10(uint16_t adc);

/* 读 DO 的开关量：返回 1 表示“超过阈值”（报警），0 表示正常。
 * 极性由 NTC.c 里的 NTC_DO_ACTIVE_LOW 决定；LM393 模块 DO 通常是开漏低有效。 */
uint8_t NTC_IsAlarm(void);

#endif
