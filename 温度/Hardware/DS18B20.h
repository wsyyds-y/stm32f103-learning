#ifndef __DS18B20_H
#define __DS18B20_H

#include "stm32f10x.h"

/**
  ******************************************************************************
  * @file    DS18B20.h
  * @brief   DS18B20 数字温度传感器驱动（单总线 / 1-Wire）—— 对外接口
  *
  * 硬件连接（引脚可在 DS18B20.c 顶部的三个宏里改）：
  *   VDD -> 3.3V
  *   GND -> GND
  *   DQ  -> PB12（单总线数据线，模块自带上拉电阻；裸器件需在 DQ 与 3.3V 之间接 4.7k）
  *
  * 分辨率与转换时间：默认 12 位，分辨率 0.0625℃，一次转换最长 750ms。
  ******************************************************************************
  */

/* 初始化 DQ 引脚：使能 GPIO 时钟，把 PB12 配成开漏输出（单总线要求“线与”，
 * 主机只能拉低或释放，靠外部上拉拉高）。调用一次即可。 */
void DS18B20_Init(void);

/* 发一次复位脉冲并检测从机应答。
 * 返回 1 表示 DS18B20 在线（存在脉冲正常），返回 0 表示没检测到器件（断线/接错脚/没上拉）。
 * 每次读温度前都会自动调用，一般不需要手动调。 */
uint8_t DS18B20_Reset(void);

/* 启动一次温度转换，然后等待转换完成并读回温度。
 * temp_x10 输出的温度值，单位 0.1℃（如 256 表示 25.6℃，-55 表示 -5.5℃），已做四舍五入。
 * 返回值 0 表示成功；1 表示器件无应答；2 表示读回的数据 CRC 校验失败。
 * 注意：本函数内部会阻塞约 750ms（12 位分辨率的最长转换时间），调用间隔不要小于这个时间。 */
uint8_t DS18B20_ReadTemp(int16_t *temp_x10);

#endif
